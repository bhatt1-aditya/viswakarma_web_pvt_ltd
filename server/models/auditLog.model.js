import mongoose from "mongoose";

const auditLogSchema = new mongoose.Schema(
  {
    project: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Project",
      required: true,
      index: true,
    },
    actor: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
    actorName: {
      type: String,
      required: true,
    },
    actorRole: {
      type: String,
      required: true,
    },
    action: {
      type: String,
      required: true, // e.g. "STATUS_CHANGE", "MEMBER_ASSIGNED", "TASK_COMPLETED", "BUG_LOGGED", "MEETING_SCHEDULED"
    },
    description: {
      type: String,
      required: true,
    },
    metadata: {
      type: mongoose.Schema.Types.Mixed,
      default: {},
    },
  },
  {
    timestamps: { createdAt: true, updatedAt: false }, // immutable audit trail
  }
);

export default mongoose.model("AuditLog", auditLogSchema);
